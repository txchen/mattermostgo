//go:build ignore

// gen_emoji writes emoji_table.go: the emoji names Mattermost uses, which
// are those of iamcal/emoji-data, the text of each emoji, the emoji picker's
// categories in their order, and the skin tone variants, which Mattermost
// names <name>_light_skin_tone and so on.
//
//	go run gen_emoji.go
package main

import (
	"encoding/json"
	"fmt"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

const source = "https://raw.githubusercontent.com/iamcal/emoji-data/v16.0.0/emoji.json"

// tones are the skin tone modifiers, with the suffix of their names.
var tones = []struct{ code, suffix string }{
	{"1F3FB", "_light_skin_tone"}, {"1F3FC", "_medium_light_skin_tone"}, {"1F3FD", "_medium_skin_tone"},
	{"1F3FE", "_medium_dark_skin_tone"}, {"1F3FF", "_dark_skin_tone"},
}

// categories are those of the picker, in its order, as the webapp's.
var categories = []string{"Smileys & Emotion", "People & Body", "Animals & Nature", "Food & Drink", "Activities", "Travel & Places", "Objects", "Symbols", "Flags"}

func text(unified string) string {
	var s strings.Builder
	for _, hex := range strings.Split(unified, "-") {
		r, err := strconv.ParseUint(hex, 16, 32)
		if err != nil {
			log.Fatal(err)
		}
		s.WriteRune(rune(r))
	}
	return s.String()
}

func main() {
	res, err := http.Get(source)
	if err != nil {
		log.Fatal(err)
	}
	defer res.Body.Close()
	var data []struct {
		Unified        string   `json:"unified"`
		ShortNames     []string `json:"short_names"`
		Category       string   `json:"category"`
		SortOrder      int      `json:"sort_order"`
		SkinVariations map[string]struct {
			Unified string `json:"unified"`
		} `json:"skin_variations"`
	}
	if err := json.NewDecoder(res.Body).Decode(&data); err != nil {
		log.Fatal(err)
	}
	sort.Slice(data, func(i, j int) bool { return data[i].SortOrder < data[j].SortOrder })
	table := map[string]string{}
	toned := map[string]bool{}
	byCategory := map[string][]string{}
	for _, e := range data {
		for _, name := range e.ShortNames {
			table[name] = text(e.Unified)
		}
		name := e.ShortNames[0]
		byCategory[e.Category] = append(byCategory[e.Category], name)
		for _, t := range tones {
			if v, ok := e.SkinVariations[t.code]; ok {
				table[name+t.suffix] = text(v.Unified)
				toned[name] = true
			}
		}
	}
	names := make([]string, 0, len(table))
	for n := range table {
		names = append(names, n)
	}
	sort.Strings(names)
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen_emoji.go from %s; DO NOT EDIT.\n\npackage markdown\n\nvar emojis = map[string]string{\n", source)
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %q,\n", n, table[n])
	}
	b.WriteString("}\n\nvar emojiCategories = []EmojiCategory{\n")
	for _, c := range categories {
		fmt.Fprintf(&b, "\t{%q, []string{", c)
		for i, n := range byCategory[c] {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", n)
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n\nvar skinToned = map[string]bool{\n")
	tonedNames := make([]string, 0, len(toned))
	for n := range toned {
		tonedNames = append(tonedNames, n)
	}
	sort.Strings(tonedNames)
	for _, n := range tonedNames {
		fmt.Fprintf(&b, "\t%q: true,\n", n)
	}
	b.WriteString("}\n")
	if err := os.WriteFile("emoji_table.go", []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Println(len(names), "names")
}
