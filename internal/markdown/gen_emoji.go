//go:build ignore

// gen_emoji writes emoji_table.go: the emoji names Mattermost uses, which
// are those of iamcal/emoji-data, and the text of each emoji.
//
//	go run gen_emoji.go
package main

import (
	"encoding/json"
	"fmt"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

const source = "https://raw.githubusercontent.com/iamcal/emoji-data/v16.0.0/emoji.json"

func main() {
	res, err := http.Get(source)
	if err != nil {
		log.Fatal(err)
	}
	defer res.Body.Close()
	var data []struct {
		Unified    string   `json:"unified"`
		ShortNames []string `json:"short_names"`
	}
	if err := json.NewDecoder(res.Body).Decode(&data); err != nil {
		log.Fatal(err)
	}
	table := map[string]string{}
	for _, e := range data {
		var s strings.Builder
		for _, hex := range strings.Split(e.Unified, "-") {
			r, err := strconv.ParseUint(hex, 16, 32)
			if err != nil {
				log.Fatal(err)
			}
			s.WriteRune(rune(r))
		}
		for _, name := range e.ShortNames {
			table[name] = s.String()
		}
	}
	names := make([]string, 0, len(table))
	for n := range table {
		names = append(names, n)
	}
	sort.Strings(names)
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen_emoji.go from %s; DO NOT EDIT.\n\npackage markdown\n\nvar emojis = map[string]string{\n", source)
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %q,\n", n, table[n])
	}
	b.WriteString("}\n")
	if err := os.WriteFile("emoji_table.go", []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Println(len(names), "names")
}
